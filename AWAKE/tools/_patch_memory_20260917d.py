def load(path):
    with io.open(path, "r", encoding="utf-8") as fh:
        return fh.read().split("\n")


def save(path, lines):
    with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def replace_line(lines, prefix, newline, path):
    idx = [i for i, ln in enumerate(lines) if ln.startswith(prefix)]
    if len(idx) != 1:
        sys.exit("%s：行首特征命中 %d 次（需要 1 次）：%r" % (path, len(idx), prefix))
    lines[idx[0]] = newline
    return idx[0]


def replace_text(lines, old, new, path):
    """行内替换；找不到不算致命（打印警告），但要报出来，绝不静默。"""
    hit = 0
    for i, ln in enumerate(lines):
        if old in ln:
            lines[i] = ln.replace(old, new)
            hit += 1
    if hit == 0:
        print("  ⚠️ 未命中（片段可能用了别的引号，需人工看）：%r" % old[:30])
    return hit


def insert_before(lines, prefix, block):
    idx = [i for i, ln in enumerate(lines) if ln.startswith(prefix)]
    if len(idx) != 1:
        sys.exit("插入锚点命中 %d 次（需要 1 次）：%r" % (len(idx), prefix))
    lines[idx[0]:idx[0]] = block
    return idx[0]



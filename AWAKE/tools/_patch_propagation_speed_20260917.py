def load(p):
    with io.open(p, "r", encoding="utf-8") as fh:
        return fh.read().split("\n")


def save(p, lines):
    with io.open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def replace_line(lines, prefix, newlines, path):
    idx = [i for i, ln in enumerate(lines) if ln.startswith(prefix)]
    if len(idx) != 1:
        sys.exit("%s：行首特征命中 %d 次（需要 1 次）：%r" % (path, len(idx), prefix))
    lines[idx[0]:idx[0] + 1] = newlines
    return idx[0]


def warn_replace(lines, old, new):
    hit = 0
    for i, ln in enumerate(lines):
        if old in ln:
            lines[i] = ln.replace(old, new)
            hit += 1
    if hit == 0:
        print("  ⚠️ 未命中：%r" % old[:36])
    return hit


